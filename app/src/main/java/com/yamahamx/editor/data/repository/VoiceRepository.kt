    /**
     * Filters voices by query text and optional category, including User Voices when provided.
     */
    fun searchVoices(
        query: String = "",
        category: String? = null,
        userVoices: List<YamahaVoice> = emptyList()
    ): List<YamahaVoice> {
        val trimmedQuery = query.trim().lowercase()
        val filterCat = if (category.isNullOrBlank() || category.equals("ALL", ignoreCase = true)) null else category.uppercase()

        val allVoices = if (userVoices.isNotEmpty()) userVoices + VOICES else VOICES

        return allVoices.filter { voice ->
            val isUserVoice = (voice.msb == 63 && voice.lsb == 8) ||
                    voice.category.equals("USER", ignoreCase = true) ||
                    voice.category.equals("USR", ignoreCase = true)

            val matchesCategory = when {
                filterCat == null -> true
                filterCat == "USER" || filterCat == "USR" -> isUserVoice
                else -> !isUserVoice && voice.category.equals(filterCat, ignoreCase = true)
            }

            val matchesQuery = trimmedQuery.isEmpty() ||
                    voice.name.lowercase().contains(trimmedQuery) ||
                    voice.subCategory.lowercase().contains(trimmedQuery) ||
                    voice.bankName.lowercase().contains(trimmedQuery) ||
                    voice.category.lowercase().contains(trimmedQuery)
            matchesCategory && matchesQuery
        }
    }
